"""Create permanent Jekyll pages for newly added CMS recipes.

The canonical sitemap is generated by Jekyll from site.pages, so adding a
recipe page automatically makes it eligible for the sitemap at build time.
Existing recipe URLs and source data are left unchanged.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
NEW_URLS = []

for data in sorted((ROOT / "_data/recipes").glob("*.json")):
    slug = data.stem
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise SystemExit(f"Unsafe recipe filename: {data.name}")
    wrapper = ROOT / "recipes" / f"{slug}.html"
    if not wrapper.exists():
        wrapper.write_text(
            f"---\nlayout: recipe\nrecipe_key: {slug}\n---\n",
            encoding="utf-8",
        )
        NEW_URLS.append(f"/recipes/{slug}.html")

print(f"Added {len(NEW_URLS)} permanent recipe pages; sitemap is generated by Jekyll.")
